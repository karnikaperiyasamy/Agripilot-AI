/**
 * Universal dynamic lookup helper to translate dynamic strings like crop names,
 * soils, statuses, or units seamlessly in any component.
 */
export function translateDynamic(text: string | null | undefined, lang: Language): string {
  if (!text) return '';
  const currentDict = translations[lang] || translations.en;

  // 1. Check crops
  if (currentDict.crops && (currentDict.crops as any)[text]) {
    return (currentDict.crops as any)[text];
  }

  // 2. Check statuses
  if (currentDict.statuses && (currentDict.statuses as any)[text]) {
    return (currentDict.statuses as any)[text];
  }

  // 3. Check soils
  if (currentDict.soils && (currentDict.soils as any)[text]) {
    return (currentDict.soils as any)[text];
  }

  // 4. Return original if no translation exists
  return text;
}
